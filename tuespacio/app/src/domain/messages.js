const catalogs = { es, en };

export function message(code, lang = 'es', params = {}) {
  const cat = catalogs[lang] || es;
  const text = cat[code] || es[code] || code;
  return text.replace(/\{(\w+)\}/g, (_, k) => (params[k] !== undefined ? String(params[k]) : ''));
}

export function pickLanguage(acceptLanguage = '') {
  const first = String(acceptLanguage).split(',')[0].trim().slice(0, 2).toLowerCase();
  return catalogs[first] ? first : 'es';
}

// Traduce un mapa { campo: CODIGO } a { campo: mensaje }.
export const translateFields = (fields, lang, params = {}) =>
  Object.fromEntries(Object.entries(fields).map(([k, code]) => [k, message(code, lang, params[k] || {})]));

export const MESSAGE_CODES = Object.keys(es);
